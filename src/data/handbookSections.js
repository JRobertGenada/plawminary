export const ALL_HANDBOOK_SECTIONS = HANDBOOK_CHAPTERS.flatMap(ch =>
  ch.sections.map(s => ({ ...s, chapterTitle: ch.title, chapterId: ch.id }))
);

export const TOTAL_HANDBOOK_SECTIONS = ALL_HANDBOOK_SECTIONS.length;

export function findSectionByPage(page) {
  if (!page) return null;
  // Sections are usually ordered by page. Find the last section that starts on or before this page.
  let found = null;
  for (const section of ALL_HANDBOOK_SECTIONS) {
    if (section.page <= page) {
      found = section;
    } else {
      break;
    }
  }
  return found;
}
